"""
Pydantic models for RAG evaluation: samples, metric scores, and reports.
Used by the Ragas evaluator and MLflow tracker.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class RAGSample(BaseModel):
    """A single question-answer-context tuple for RAG evaluation."""

    question: str = Field(description="The question posed to the RAG system")
    answer: str = Field(description="The answer generated by the RAG system")
    contexts: list[str] = Field(description="Retrieved context chunks used to generate the answer")
    ground_truth: str | None = Field(
        default=None, description="Reference answer for supervised metrics"
    )
    metadata: dict[str, Any] = Field(default_factory=dict)


class MetricScore(BaseModel):
    """A single metric measurement for one evaluation sample."""

    name: str = Field(description="Metric name, e.g. 'faithfulness'")
    score: float = Field(description="Score value in [0, 1]", ge=0.0, le=1.0)
    details: dict[str, Any] = Field(default_factory=dict)


class EvaluationResult(BaseModel):
    """Per-sample evaluation result containing all metric scores."""

    sample: RAGSample
    metrics: list[MetricScore]
    evaluated_at: datetime = Field(default_factory=datetime.utcnow)


class EvaluationReport(BaseModel):
    """
    Aggregated report for a complete evaluation run.
    Logged to MLflow as an artifact.
    """

    run_id: str = Field(description="Unique evaluation run identifier")
    experiment_name: str
    num_samples: int = Field(ge=0)
    aggregate_metrics: dict[str, float] = Field(
        description="Mean metric scores across all samples"
    )
    results: list[EvaluationResult]
    pipeline_version: str = "0.1.0"
    evaluated_at: datetime = Field(default_factory=datetime.utcnow)
    metadata: dict[str, Any] = Field(default_factory=dict)
